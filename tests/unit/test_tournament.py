def test_tournament_run(tmp_path, mock_task, mock_arena, mock_judge_orchestrator):
    """Test running a tournament."""
    dut1 = MockDUT("dut_a", {})
    dut2 = MockDUT("dut_b", {})

    cache = SolutionCache(tmp_path / "cache")

    runner = TournamentRunner(
        duts=[dut1, dut2],
        tasks=[mock_task],
        judges=mock_judge_orchestrator,
        arenas=[mock_arena],
        cache=cache,
        samples_per_pairing=2,
    )

    result = runner.run()

    # Verify result structure
    assert len(result.ratings) == 2
    assert "dut_a" in result.ratings
    assert "dut_b" in result.ratings

    # Verify comparisons were made
    # 1 task × 1 arena × 1 pair × 2 samples = 2 comparisons
    assert result.total_comparisons == 2
    assert len(result.comparisons) == 2

    # Verify ratings were updated
    rating_a = result.ratings["dut_a"]
    rating_b = result.ratings["dut_b"]

    # dut_a < dut_b alphabetically, so dut_a should win
    assert rating_a.wins + rating_a.losses + rating_a.ties == 2
    assert rating_b.wins + rating_b.losses + rating_b.ties == 2

    # Verify ELO is updated (not initial value)
    assert rating_a.elo != 1500  # Initial value

    # Verify cost tracking
    assert rating_a.total_cost_usd > 0
    assert rating_b.total_cost_usd > 0
    assert result.total_cost_usd == rating_a.total_cost_usd + rating_b.total_cost_usd


