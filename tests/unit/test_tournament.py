def test_tournament_caching(tmp_path, mock_task, mock_arena, mock_judge_orchestrator):
    """Test that tournament uses cached solutions."""
    dut = MockDUT("dut1", {})

    cache = SolutionCache(tmp_path / "cache")

    runner = TournamentRunner(
        duts=[dut],
        tasks=[mock_task],
        judges=mock_judge_orchestrator,
        arenas=[mock_arena],
        cache=cache,
        samples_per_pairing=1,
    )

    # First run - generates solution
    result1 = runner.run()

    # Create new runner with same cache
    runner2 = TournamentRunner(
        duts=[dut],
        tasks=[mock_task],
        judges=mock_judge_orchestrator,
        arenas=[mock_arena],
        cache=cache,
        samples_per_pairing=1,
    )

    # Second run - should use cached solution
    result2 = runner2.run()

    # Both should have same cost (cached solution reused)
    assert result1.ratings["dut1"].total_cost_usd == result2.ratings["dut1"].total_cost_usd


def test_dut_rating_properties():
    """Test DUTRating property calculations."""
    from codegen_bench.core.tournament import DUTRating
    from codegen_bench.stats.ratings.bayesian_elo import BayesianELO

    rating = DUTRating(
        dut_id="test",
        rating=BayesianELO(prior_mean=1500, prior_std=200),
        wins=10,
        losses=5,
        ties=2,
        total_cost_usd=1.5,
        total_time_seconds=30.0,
        total_tokens=1000,
    )

    assert rating.elo == 1500
    assert rating.elo_std == 200
    assert rating.elo_lower_bound == 1500 - 2 * 200
    assert rating.elo_upper_bound == 1500 + 2 * 200
    assert rating.wins == 10
    assert rating.losses == 5
    assert rating.ties == 2
